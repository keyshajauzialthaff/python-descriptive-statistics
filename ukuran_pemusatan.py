import math

def mean(data):
    return sum(data) / len(data)

"""**2. Median**"""

def median(data):
    n = len(data)
    data_sorted = sorted(data)
    tengah = n // 2
    if n % 2 == 0: #untuk angka genap
        return (data_sorted[tengah - 1] + data_sorted[tengah]) / 2
    else: #selain angka genap (ganjil)
        return data_sorted[tengah]

"""**3. Modus**"""

def modus(data):
    frekuensi = {}
    for i in data:
        frekuensi[i] = frekuensi.get(i, 0) + 1
    maksimum = max(frekuensi.values())
    modus_list = [k for k, v in frekuensi.items() if v == maksimum]
    if len(modus_list) == len(data):  # jika tidak ada modus
        return None
    return modus_list

"""**4. Kuartil**"""

def kuartil(data, q):
    data_sorted = sorted(data)
    n = len(data)
    pos = (n + 1) * q / 4
    bawah = math.floor(pos) - 1
    atas = math.ceil(pos) - 1

    if bawah == atas:
        return data_sorted[bawah]
    else:
        return data_sorted[bawah] + (pos - (bawah + 1)) * (data_sorted[atas] - data_sorted[bawah])

def ukuran_pemusatan(data):
    return {
        "Rata-rata": mean(data),
        "Median": median(data),
        "Modus": modus(data),
        "Kuartil 1 (Q1)": kuartil(data, 1),
        "Kuartil 3 (Q3)": kuartil(data, 3)
    }