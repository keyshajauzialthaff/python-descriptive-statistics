def nilai_minimum(data):
    return min(data)

"""**2. Maksimum**"""

def nilai_maksimum(data):
    return max(data)

"""**3. Range**"""

def rentang(data):
    return nilai_maksimum(data) - nilai_minimum(data)

"""**4. Varians**"""

def varians(data):
    n = len(data)
    mean = sum(data) / n
    return sum((x - mean) ** 2 for x in data) / (n - 1)

"""**5. Standar Deviasi**"""

def standar_deviasi(data):
    return varians(data)** 0.5

def ukuran_penyebaran(data):
    return {
        "Nilai Minimum": nilai_minimum(data),
        "Nilai Maksimum": nilai_maksimum(data),
        "Range": rentang(data),
        "Varians": varians(data),
        "Standar Deviasi": standar_deviasi(data)
    }